export const NO_INFO = "Одоогоор баталгаажсан мэдээлэл олдсонгүй.";

export function annLine(a: Announcement): string {
  const where = [a.location.sum, a.location.bag, a.location.area].filter(Boolean).join(", ") + (a.locationNote ? ` (${a.locationNote})` : "");
  const when = a.start ? `${fmtDate(a.start, true)}${a.end ? " – " + fmtDate(a.end, true) : ""}` : "цаг тодорхойгүй";
  return `[${VERIFY[a.verification].label}] ${a.organization}: ${a.title}. Ангилал: ${ANN_CAT[a.category].label}. Байршил: ${where}. Хугацаа: ${when}. Товч: ${a.summary} Эх сурвалж: ${a.sourceUrl}. Нийтэлсэн: ${fmtDate(a.publishedAt)}. Шалгасан: ${fmtDate(a.checkedAt, true)}.`;
}

export async function buildContext(): Promise<{ text: string; anns: Announcement[]; traffic: TrafficSnapshot }> {
  const [{ items }, traffic, garbage, alerts, bus, weather] = await Promise.all([
    collectAnnouncements(), getTraffic(),
    garbageContext().catch(() => "ХОГ АЧИЛТЫН ХУВААРЬ: одоогоор уншиж чадсангүй."),
    alertsContext().catch(() => "ШУУРХАЙ МЭДЭЭЛЭЛ: одоогоор уншиж чадсангүй."),
    busContext().catch(() => "АВТОБУСНЫ ЧИГЛЭЛ: одоогоор уншиж чадсангүй."),
    getWeather().then(weatherContext),
  ]);
  const issues = DEMO_ISSUES.map((i) => `[Жишээ] ${i.id} ${i.title} — ${ISSUE_CAT[i.category]}, ${i.area}, төлөв: ${STATUS[i.status].label}${i.action ? ", авсан арга хэмжээ: " + i.action : ""}${i.resolvedAt ? ", шийдсэн: " + fmtDate(i.resolvedAt) : ""}.`);
  const text = [
    alerts,
    "",
    "МЭДЭГДЛҮҮД:",
    ...items.map(annLine),
    "",
    trafficContext(traffic),
    "",
    garbage,
    "",
    bus,
    "",
    weather,
    "",
    servicesContext(Date.now()),
    "",
    visitorContext(),
    "",
    "ИРГЭДИЙН АСУУДЛУУД (бүгд жишээ өгөгдөл):",
    ...issues,
    "",
    "АСУУДАЛ МЭДЭЭЛЭХ: сайтын «Асуудал мэдээлэх» хэсэгт гарчиг, ангилал, байршил, тайлбар, зураг оруулаад илгээнэ. Хяналтын дугаар өгнө. Мэдээлэл SMART ORKHON-ий санд хадгалагдах бөгөөд албан байгууллагад автоматаар илгээгдэхгүй.",
    "ЯАРАЛТАЙ УТАС: 101 гал, 102 цагдаа, 103 түргэн тусламж, 105 онцгой байдал, 11-11 санал гомдол.",
  ].join("\n");
  return { text, anns: items, traffic };
}

